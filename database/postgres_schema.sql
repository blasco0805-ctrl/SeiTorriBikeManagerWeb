CREATE TABLE IF NOT EXISTS allegati_circuiti (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuito_id BIGINT,
    nome_file TEXT,
    percorso_file TEXT
);

CREATE TABLE IF NOT EXISTS allegati_gare (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gara_id BIGINT,
    nome_file TEXT,
    percorso_file TEXT
);

CREATE TABLE IF NOT EXISTS allegati_soci (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT,
    nome_file TEXT,
    percorso_file TEXT
);

CREATE TABLE IF NOT EXISTS certificati (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT,
    data_scadenza TEXT,
    note TEXT
);

CREATE TABLE IF NOT EXISTS circuiti (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS gare (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT,
    luogo TEXT,
    data TEXT,
    tipologia TEXT,
    distanza TEXT,
    dislivello TEXT,
    descrizione TEXT,
    circuito TEXT
);

CREATE TABLE IF NOT EXISTS partecipanti_gare (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gara_id BIGINT,
    socio_id BIGINT,
    stato TEXT
);

CREATE TABLE IF NOT EXISTS partecipazioni (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gara_id BIGINT,
    socio_id BIGINT,
    stato TEXT
);

CREATE TABLE IF NOT EXISTS soci (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT,
    cognome TEXT,
    telefono TEXT,
    email TEXT,
    categoria TEXT,
    note TEXT
);

CREATE TABLE IF NOT EXISTS trasferte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gara_id BIGINT,
    destinazione TEXT,
    data_partenza TEXT,
    mezzo TEXT,
    note TEXT
);

CREATE TABLE IF NOT EXISTS utenti (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT,
    password TEXT,
    ruolo TEXT,
    socio_id BIGINT
);